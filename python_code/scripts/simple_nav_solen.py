#!/usr/bin/env python3
"""Простейший сценарий навигации по магнитному маяку.

Что делает скрипт:
  1. Создаёт маяк (вращающийся магнитный диполь) в начале координат.
  2. Строит прямолинейную траекторию в допустимом квадранте (первый октант).
  3. Добавляет гауссов шум к a/b-параметрам (гармонические составляющие поля).
  4. Показывает окно с истинной и восстановленной (зашумлённой) траекториями.

Запуск:
    uv run python scens/simple_line.py
    # или просто:
    python scens/simple_line.py
"""

from __future__ import annotations

import os
import sys

import matplotlib.pyplot as plt
import numpy as np

# ── Подключаем пакет (если запускаем из корня проекта) ──────────────────
sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

from mag_nav import (
    GaussianNoise,  # аддитивный гауссов шум
    QuadrantPolicy,
    RotatingDipole,  # модель маяка: вращающийся магнитный диполь
    Scenario,  # «прогон»: источник + траектория + шум → результат
    Solenoid,
    radial_rays,  # генератор траектории: лучи из начала координат
)
from mag_nav.sim import visualize as viz  # готовые функции отрисовки

# =====================================================================
# 1. МАЯК
# =====================================================================
# Вращающийся магнитный диполь — это модель катушки-маяка,
# вращающейся вокруг своей оси.  Единственный параметр источника,
# который влияет на поле в дальней зоне, — дипольная константа  B0.
#
#   B0 = μ₀/(4π) · m  =  1e-7 · m      [Тл·м³]
#
# где m — магнитный момент катушки.  Для типичной катушки
# (N = 150 витков, I = 3 А, R = 5 см) момент ≈ 3.5 А·м²,
# что даёт B0 ≈ 3.5e-7 Тл·м³.

# beacon = RotatingDipole(
#     origin=np.array([0.0, 0.0, 0.0]),  # маяк стоит в начале координат
#     b0=3.5e-7,  # дипольная константа [Тл·м³]
#     quadrant_policy=QuadrantPolicy.STRICT,  # навигация работает в 1-м октанте
# )

beacon = Solenoid.from_b0(
    origin=np.array([0.0, 0.0, 0.0]),  # маяк стоит в начале координат
    b0=3.5e-7,  # дипольная константа [Тл·м³]
    quadrant_policy=QuadrantPolicy.STRICT,  # навигация работает в 1-м октанте
    radius=0.05,
    length=0.30,
)

print(f"Маяк: B0 = {beacon.dipole_constant:.3e} Тл·м³, позиция = {beacon.origin}")


# =====================================================================
# 2. ТРАЕКТОРИЯ — прямая линия в допустимом квадранте
# =====================================================================
# radial_rays(n_rays, radii, elevation_deg, azimuth_deg)
#   генерирует точки вдоль лучей из начала координат.
#   Один луч  →  одна прямая линия.
#
# Углы задают направление луча в сферических координатах:
#   elevation (возвышение)  — угол от плоскости xOy вверх,
#   azimuth   (азимут)     — угол в плоскости xOy от оси x.
#
# Для первого октанта оба угла ∈ (0°, 90°).

n_points = 120  # число точек на траектории
r_start = np.array([0.5, 0.5, 0.5])
r_end = np.array([0.01, 0.01, 0.1])

trajectory = np.array(
    [
        np.linspace(r_start[0], r_end[0], n_points),
        np.linspace(r_start[1], r_end[1], n_points),
        np.linspace(r_start[2], r_end[2], n_points),
    ]
).T
# trajectory — массив (n_points, 3): координаты [x, y, z] каждой точки

print(f"Траектория: {n_points} точек, r = [{r_start} … {r_end}]")


# =====================================================================
# 3. ШУМ
# =====================================================================
# Навигационный алгоритм работает с a/b-параметрами — амплитудами
# двух квадратурных гармоник, извлечённых из сигнала датчика.
# Шум «инжектируется» именно в эти параметры (inject_at="ab").
#
# GaussianNoise(sigma, relative=True)
#   sigma    — стандартное отклонение,
#   relative — если True, sigma задаётся *доля* от значения
#              (т. е. 0.02 = 2 %).

sigma = 1e-3
noise = GaussianNoise(sigma=sigma, relative=True)  # 3 % относительного шума
print(f"Шум: гауссов, σ = {sigma * 100} % (относительный)")


# =====================================================================
# 4. ПРОГОН СЦЕНАРИЯ
# =====================================================================
# Scenario собирает всё вместе и выполняет навигационный расчёт:
#   источник → поле в точках траектории → a/b-параметры
#   → (+ шум, если задан) → обратное восстановление координат.

result = Scenario(
    source=beacon,
    trajectory=trajectory,
    noise=noise,
    inject_at="ab",  # шум добавляется к a/b-параметрам
    seed=42,  # фиксируем ГСЧ для воспроизводимости
).run()

print(result.summary())


# =====================================================================
# 5. ВИЗУАЛИЗАЦИЯ
# =====================================================================
# Рисуем в одном 3D-окне:
#   • истинную траекторию  (прямая линия, синий),
#   • восстановленную      (кривоватая из-за шума, красный),
#   • положение маяка        (чёрная звезда).

viz.apply_style()  # единый стиль оформления графиков

fig = plt.figure(figsize=(9, 7))
ax = fig.add_subplot(111, projection="3d")

# --- истинная траектория (то, что задали) ---
ax.plot(
    trajectory[:, 0],
    trajectory[:, 1],
    trajectory[:, 2],
    color="tab:blue",
    linewidth=2,
    label="Истинная траектория",
)

# --- восстановленная траектория (то, что вернул алгоритм) ---
est = result.estimated_positions  # (n_points, 3)
ax.plot(
    est[:, 0],
    est[:, 1],
    est[:, 2],
    color="tab:red",
    linewidth=1.4,
    alpha=0.85,
    label=f"Восстановленная (с шумом {sigma * 100} %)",
)

# --- маяк ---
ax.scatter(*beacon.origin, color="black", s=120, marker="*", zorder=5, label="Маяк")

# --- оформление ---
ax.set_xlabel("x, м")
ax.set_ylabel("y, м")
ax.set_zlabel("z, м")
ax.set_title("Навигация по магнитному маяку — прямая линия с шумом")
ax.legend(loc="upper left", fontsize=9)
fig.tight_layout()

plt.show()  # ← открывает интерактивное окно

print("Готово.")

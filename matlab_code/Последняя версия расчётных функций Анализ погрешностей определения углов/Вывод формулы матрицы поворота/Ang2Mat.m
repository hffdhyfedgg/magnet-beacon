function matr = Ang2Mat(alf, bet, gam)
    matr = [1,          0,          0;...
            0,          cos(alf),   -sin(alf);...
            0,          sin(alf),   cos(alf)]*...
           [cos(bet),   0,          sin(bet);...
            0,          1,          0;...
            -sin(bet),  0,          cos(bet)]*...
           [cos(gam),   -sin(gam),  0;...
            sin(gam),   cos(gam),   0;...
            0,          0,          1];
        
end
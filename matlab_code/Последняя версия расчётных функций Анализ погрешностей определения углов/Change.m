
%  asq = v(1,1,:).^2+v(2,1,:).^2+v(3,1,:).^2;
%  bsq = v(1,2,:).^2+v(2,2,:).^2+v(3,2,:).^2;    
% 
%  sz = [size(v), 1];
%     

filename = "CalcRotMatrix.m";

f = fopen(filename);

var = [...
    "ax\(i\)", "v(1,1,:)";...
    "ay\(i\)", "v(2,1,:)";...
    "az\(i\)", "v(3,1,:)";...
    "bx\(i\)", "v(1,2,:)";...
    "by\(i\)", "v(2,2,:)";...
    "bz\(i\)", "v(3,2,:)";...
    "\*", "\.\*";...
    "/", "./";...
    "\^", "\.\^";...
    "v\(1,1,:\)\.\^2+v\(2,1,:\)\.\^2+v\(3,1,:\)\.\^2", "asq";...
    "-v\(1,1,:\)\.\^2-v\(2,1,:\)\.\^2-v\(3,1,:\)\.\^2", "asq";...
    "v\(1,2,:\)\.\^2+v\(2,2,:\)\.\^2+v\(3,2,:\)\.\^2", "bsq";...
    "-v\(1,2,:\)\.\^2-v\(2,2,:\)\.\^2-v\(3,2,:\)\.\^2", "-bsq";...
    ];

while ~feof(f)
    s = fgetl(f);
    for i = 1:size(var,1)
        s = regexprep(s, var(i,1), var(i,2));
    end
    disp(s)
end
disp("  ")



